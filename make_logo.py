data = bytearray()
for line in logo_ascii:
    for i in range(0, 32, 8):
        byte_str = line[i:i+8]
        data.append(int(byte_str, 2))

print("Creating logo.pbm (Waveshare Logo)...")
try:
    with open('logo.pbm', 'wb') as f:
        f.write(header)
        f.write(data)
    print("Success! logo.pbm created.")
except Exception as e:
    print(f"Error: {e}")