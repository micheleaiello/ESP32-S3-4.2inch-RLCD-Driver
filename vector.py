def draw(display, text, x, y, scale=1, c=1, thickness=1):
    start_x = x
    char_width = 12 * scale
    
    for char in text:
        char = char.upper()
        if char == '\n':
            y += 15 * scale
            x = start_x
            continue
        if char == ' ':
            x += char_width
            continue
            
        if char in FONT:
            strokes = FONT[char]
            if len(strokes) > 1:
                curr_x = strokes[0]
                curr_y = strokes[1]
                i = 2
                while i < len(strokes):
                    next_x = strokes[i]
                    next_y = strokes[i+1]
                    
                    if next_x == -1: # Pen Lift
                        i += 2
                        if i < len(strokes):
                            curr_x = strokes[i]
                            curr_y = strokes[i+1]
                            i += 2
                        continue
                        
                    # Calculate scaled coordinates
                    x1 = int(x + curr_x * scale)
                    y1 = int(y + curr_y * scale)
                    x2 = int(x + next_x * scale)
                    y2 = int(y + next_y * scale)
                    
                    # Draw Main Line
                    display.line(x1, y1, x2, y2, c)
                    
                    # Draw Thick Lines (Offset by 1px)
                    if thickness > 1:
                        # Draw parallel line X+1
                        display.line(x1+1, y1, x2+1, y2, c)
                    if thickness > 2:
                        # Draw parallel line Y+1
                        display.line(x1, y1+1, x2, y2+1, c)
                    
                    curr_x = next_x
                    curr_y = next_y
                    i += 2
        x += char_width